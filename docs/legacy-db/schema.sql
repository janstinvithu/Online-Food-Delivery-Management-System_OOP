-- =============================================================================
-- ONLINE FOOD DELIVERY MANAGEMENT SYSTEM - SRI LANKA EDITION (LKR)
-- Database Relational Schema Definition (DDL)
-- =============================================================================

DROP TABLE IF EXISTS card_payments CASCADE;
DROP TABLE IF EXISTS cash_payments CASCADE;
DROP TABLE IF EXISTS payments CASCADE;
DROP TABLE IF EXISTS order_items CASCADE;
DROP TABLE IF EXISTS pickup_orders CASCADE;
DROP TABLE IF EXISTS online_orders CASCADE;
DROP TABLE IF EXISTS food_orders CASCADE;
DROP TABLE IF EXISTS deliveries CASCADE;
DROP TABLE IF EXISTS delivery_persons CASCADE;
DROP TABLE IF EXISTS customers CASCADE;
DROP TABLE IF EXISTS beverages CASCADE;
DROP TABLE IF EXISTS main_courses CASCADE;
DROP TABLE IF EXISTS food_items CASCADE;

-- -----------------------------------------------------------------------------
-- Component 01: FoodItem Hierarchy (Joined Table Inheritance)
-- -----------------------------------------------------------------------------
CREATE TABLE food_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_type VARCHAR(31) NOT NULL,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(255),
    price NUMERIC(10, 2) NOT NULL,
    available BOOLEAN NOT NULL DEFAULT TRUE,
    preparation_time_minutes INT NOT NULL,
    CONSTRAINT chk_food_price CHECK (price > 0.00),
    CONSTRAINT chk_prep_time CHECK (preparation_time_minutes > 0)
);

CREATE TABLE main_courses (
    id BIGINT PRIMARY KEY,
    cuisine_type VARCHAR(50) NOT NULL,
    is_vegetarian BOOLEAN NOT NULL,
    spice_level VARCHAR(20) NOT NULL,
    serving_portion VARCHAR(50) NOT NULL,
    CONSTRAINT fk_main_course_food FOREIGN KEY (id) REFERENCES food_items(id) ON DELETE CASCADE,
    CONSTRAINT chk_spice_level CHECK (spice_level IN ('MILD', 'MEDIUM', 'HOT', 'EXTRA_HOT'))
);

CREATE TABLE beverages (
    id BIGINT PRIMARY KEY,
    volume_size VARCHAR(50) NOT NULL,
    volume_ml INT NOT NULL,
    is_cold BOOLEAN NOT NULL,
    caffeine_content_mg INT NOT NULL DEFAULT 0,
    sugar_level VARCHAR(20) NOT NULL,
    CONSTRAINT fk_beverage_food FOREIGN KEY (id) REFERENCES food_items(id) ON DELETE CASCADE,
    CONSTRAINT chk_volume CHECK (volume_ml > 0),
    CONSTRAINT chk_caffeine CHECK (caffeine_content_mg >= 0),
    CONSTRAINT chk_sugar_level CHECK (sugar_level IN ('ZERO', 'LOW', 'MEDIUM', 'HIGH'))
);

-- -----------------------------------------------------------------------------
-- Component 02: Customer Hierarchy (Single Table Inheritance)
-- -----------------------------------------------------------------------------
CREATE TABLE customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_type VARCHAR(31) NOT NULL,
    full_name VARCHAR(100) NOT NULL,
    email VARCHAR(120) NOT NULL UNIQUE,
    phone VARCHAR(25) NOT NULL,
    address VARCHAR(255),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    loyalty_points INT DEFAULT 0,
    membership_tier VARCHAR(20),
    password_hash VARCHAR(255),
    preferred_payment_method VARCHAR(50),
    CONSTRAINT chk_customer_type CHECK (customer_type IN ('GUEST', 'REGISTERED')),
    CONSTRAINT chk_loyalty_pts CHECK (loyalty_points >= 0),
    CONSTRAINT chk_tier CHECK (membership_tier IS NULL OR membership_tier IN ('BRONZE', 'SILVER', 'GOLD', 'PLATINUM'))
);

-- -----------------------------------------------------------------------------
-- Component 04 (Part A): Delivery Logistics Domain Entities
-- -----------------------------------------------------------------------------
CREATE TABLE delivery_persons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    phone VARCHAR(25) NOT NULL UNIQUE,
    vehicle_type VARCHAR(50) NOT NULL,
    vehicle_plate_number VARCHAR(30) NOT NULL,
    is_available BOOLEAN NOT NULL DEFAULT TRUE,
    rating NUMERIC(3, 2) NOT NULL DEFAULT 5.00,
    CONSTRAINT chk_rating CHECK (rating >= 1.00 AND rating <= 5.00)
);

CREATE TABLE deliveries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tracking_number VARCHAR(36) NOT NULL UNIQUE,
    delivery_status VARCHAR(30) NOT NULL,
    departure_time TIMESTAMP,
    delivered_time TIMESTAMP,
    delivery_person_id BIGINT,
    CONSTRAINT fk_delivery_person FOREIGN KEY (delivery_person_id) REFERENCES delivery_persons(id) ON DELETE SET NULL
);

-- -----------------------------------------------------------------------------
-- Component 03: FoodOrder Hierarchy (Joined Table Inheritance)
-- -----------------------------------------------------------------------------
CREATE TABLE food_orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number VARCHAR(36) NOT NULL UNIQUE,
    order_type VARCHAR(31) NOT NULL,
    order_status VARCHAR(30) NOT NULL,
    order_date_time TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    subtotal_amount NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    discount_amount NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    total_amount NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    customer_id BIGINT NOT NULL,
    CONSTRAINT fk_order_customer FOREIGN KEY (customer_id) REFERENCES customers(id) ON DELETE RESTRICT,
    CONSTRAINT chk_order_total CHECK (total_amount >= 0.00)
);

CREATE TABLE online_orders (
    id BIGINT PRIMARY KEY,
    delivery_address VARCHAR(255) NOT NULL,
    special_delivery_instructions VARCHAR(255),
    estimated_delivery_time TIMESTAMP,
    delivery_fee NUMERIC(10, 2) NOT NULL DEFAULT 350.00,
    delivery_id BIGINT UNIQUE,
    CONSTRAINT fk_online_order_base FOREIGN KEY (id) REFERENCES food_orders(id) ON DELETE CASCADE,
    CONSTRAINT fk_online_order_delivery FOREIGN KEY (delivery_id) REFERENCES deliveries(id) ON DELETE SET NULL,
    CONSTRAINT chk_delivery_fee CHECK (delivery_fee >= 0.00)
);

CREATE TABLE pickup_orders (
    id BIGINT PRIMARY KEY,
    pickup_time_slot VARCHAR(50) NOT NULL,
    pickup_window_minutes INT NOT NULL,
    counter_number INT NOT NULL,
    pickup_contact_phone VARCHAR(25) NOT NULL,
    is_curbside_pickup BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_pickup_order_base FOREIGN KEY (id) REFERENCES food_orders(id) ON DELETE CASCADE,
    CONSTRAINT chk_pickup_window CHECK (pickup_window_minutes > 0),
    CONSTRAINT chk_counter_num CHECK (counter_number > 0)
);

CREATE TABLE order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    food_item_id BIGINT NOT NULL,
    quantity INT NOT NULL,
    unit_price NUMERIC(10, 2) NOT NULL,
    subtotal NUMERIC(10, 2) NOT NULL,
    CONSTRAINT fk_item_order FOREIGN KEY (order_id) REFERENCES food_orders(id) ON DELETE CASCADE,
    CONSTRAINT fk_item_food FOREIGN KEY (food_item_id) REFERENCES food_items(id) ON DELETE RESTRICT,
    CONSTRAINT chk_item_quantity CHECK (quantity > 0),
    CONSTRAINT chk_item_unit_price CHECK (unit_price > 0.00),
    CONSTRAINT chk_item_subtotal CHECK (subtotal >= 0.00)
);

-- -----------------------------------------------------------------------------
-- Component 04 (Part B): Payment Hierarchy (Joined Table Inheritance)
-- -----------------------------------------------------------------------------
CREATE TABLE payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_type VARCHAR(31) NOT NULL,
    order_id BIGINT NOT NULL UNIQUE,
    amount NUMERIC(10, 2) NOT NULL,
    payment_status VARCHAR(30) NOT NULL,
    payment_timestamp TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    transaction_reference VARCHAR(64) NOT NULL UNIQUE,
    CONSTRAINT fk_payment_order FOREIGN KEY (order_id) REFERENCES food_orders(id) ON DELETE CASCADE,
    CONSTRAINT chk_payment_amount CHECK (amount > 0.00)
);

CREATE TABLE cash_payments (
    id BIGINT PRIMARY KEY,
    amount_tendered NUMERIC(10, 2) NOT NULL,
    change_due NUMERIC(10, 2) NOT NULL DEFAULT 0.00,
    CONSTRAINT fk_cash_payment_base FOREIGN KEY (id) REFERENCES payments(id) ON DELETE CASCADE,
    CONSTRAINT chk_cash_tendered CHECK (amount_tendered >= 0.00),
    CONSTRAINT chk_cash_change CHECK (change_due >= 0.00)
);

CREATE TABLE card_payments (
    id BIGINT PRIMARY KEY,
    card_last_four VARCHAR(4) NOT NULL,
    card_type VARCHAR(20) NOT NULL,
    authorization_code VARCHAR(50) NOT NULL,
    gateway_transaction_id VARCHAR(100) NOT NULL,
    CONSTRAINT fk_card_payment_base FOREIGN KEY (id) REFERENCES payments(id) ON DELETE CASCADE
);

-- -----------------------------------------------------------------------------
