CREATE INDEX idx_food_items_avail ON food_items(available);
CREATE INDEX idx_customers_email ON customers(email);
CREATE INDEX idx_customers_type ON customers(customer_type);
CREATE INDEX idx_food_orders_customer_id ON food_orders(customer_id);
CREATE INDEX idx_food_orders_status ON food_orders(order_status);
CREATE INDEX idx_food_orders_date ON food_orders(order_date_time);
CREATE INDEX idx_order_items_order_id ON order_items(order_id);
CREATE INDEX idx_order_items_food_id ON order_items(food_item_id);
CREATE INDEX idx_deliveries_person_id ON deliveries(delivery_person_id);
CREATE INDEX idx_deliveries_status ON deliveries(delivery_status);
CREATE INDEX idx_online_orders_delivery_id ON online_orders(delivery_id);
CREATE INDEX idx_payments_order_id ON payments(order_id);
CREATE INDEX idx_payments_status ON payments(payment_status);
